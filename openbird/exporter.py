"""
OpenBird - Multi-Format Document & Action Item Exporter
Generates professional Word (.docx), plain text (.txt), and aggregated action checklists.
"""

import os
import re
import time
import logging
from typing import List, Dict, Optional

from . import config

logger = logging.getLogger("openbird.exporter")

try:
    import docx
    from docx.shared import Inches, Pt, RGBColor
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.oxml import OxmlElement, parse_xml
    from docx.oxml.ns import nsdecls, qn
    DOCX_AVAILABLE = True
except ImportError:
    DOCX_AVAILABLE = False


def export_to_docx(markdown_text: str, output_path: str, title: str = "Meeting Notes") -> str:
    """Converts OpenBird-schema markdown notes to a polished Microsoft Word (.docx) document."""
    if not DOCX_AVAILABLE:
        raise RuntimeError("python-docx is not installed.")

    doc = docx.Document()

    # Set standard 1-inch margins
    sections = doc.sections
    for section in sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)

    # Base typography: Segoe UI / Aptos
    style_normal = doc.styles['Normal']
    font = style_normal.font
    font.name = 'Segoe UI'
    font.size = Pt(10.5)
    font.color.rgb = RGBColor(0x22, 0x22, 0x22)

    # Add Title
    title_p = doc.add_paragraph()
    title_run = title_p.add_run(title)
    title_run.font.name = 'Segoe UI Variable Display'
    title_run.font.size = Pt(22)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(0x00, 0x4E, 0x8C)
    title_p.paragraph_format.space_after = Pt(4)

    # Date Subtitle
    date_p = doc.add_paragraph()
    date_run = date_p.add_run(f"Generated by OpenBird on {time.strftime('%B %d, %Y at %H:%M')}")
    date_run.font.size = Pt(9.5)
    date_run.font.italic = True
    date_run.font.color.rgb = RGBColor(0x66, 0x66, 0x66)
    date_p.paragraph_format.space_after = Pt(16)

    # Process markdown lines
    lines = markdown_text.splitlines()
    in_code_block = False
    code_lines = []

    for line in lines:
        stripped = line.strip()

        # Code block handler
        if stripped.startswith("```"):
            if in_code_block:
                in_code_block = False
                code_text = "\n".join(code_lines)
                cp = doc.add_paragraph()
                crun = cp.add_run(code_text)
                crun.font.name = 'Cascadia Code'
                crun.font.size = Pt(9.0)
                crun.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
                cp.paragraph_format.left_indent = Inches(0.4)
                cp.paragraph_format.space_before = Pt(4)
                cp.paragraph_format.space_after = Pt(8)
                code_lines = []
            else:
                in_code_block = True
                code_lines = []
            continue

        if in_code_block:
            code_lines.append(line)
            continue

        if not stripped:
            continue

        # Headings
        if stripped.startswith("# "):
            p = doc.add_paragraph()
            r = p.add_run(stripped[2:])
            r.font.name = 'Segoe UI Variable Display'
            r.font.size = Pt(16)
            r.font.bold = True
            r.font.color.rgb = RGBColor(0x00, 0x4E, 0x8C)
            p.paragraph_format.space_before = Pt(14)
            p.paragraph_format.space_after = Pt(4)
            p.paragraph_format.keep_with_next = True
        elif stripped.startswith("## "):
            p = doc.add_paragraph()
            r = p.add_run(stripped[3:])
            r.font.name = 'Segoe UI Variable Display'
            r.font.size = Pt(13)
            r.font.bold = True
            r.font.color.rgb = RGBColor(0x11, 0x11, 0x11)
            p.paragraph_format.space_before = Pt(12)
            p.paragraph_format.space_after = Pt(4)
            p.paragraph_format.keep_with_next = True
        elif stripped.startswith("### "):
            p = doc.add_paragraph()
            r = p.add_run(stripped[4:])
            r.font.name = 'Segoe UI'
            r.font.size = Pt(11)
            r.font.bold = True
            r.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
            p.paragraph_format.space_before = Pt(8)
            p.paragraph_format.space_after = Pt(2)
            p.paragraph_format.keep_with_next = True
        elif stripped.startswith(">"):
            quote_text = stripped[1:].strip()
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.3)
            r = p.add_run(quote_text)
            r.font.italic = True
            r.font.color.rgb = RGBColor(0x44, 0x44, 0x44)
            p.paragraph_format.space_before = Pt(4)
            p.paragraph_format.space_after = Pt(6)
        elif stripped.startswith("- [ ]") or stripped.startswith("* [ ]"):
            task_text = stripped[5:].strip()
            p = doc.add_paragraph(style='List Bullet')
            box = p.add_run("☐  ")
            box.font.bold = True
            box.font.color.rgb = RGBColor(0x00, 0x78, 0xD4)
            p.add_run(task_text)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
        elif stripped.startswith("- [x]") or stripped.startswith("* [x]"):
            task_text = stripped[5:].strip()
            p = doc.add_paragraph(style='List Bullet')
            box = p.add_run("☑  ")
            box.font.bold = True
            box.font.color.rgb = RGBColor(0x10, 0x7C, 0x41)
            r = p.add_run(task_text)
            r.font.strike = True
            r.font.color.rgb = RGBColor(0x88, 0x88, 0x88)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
        elif stripped.startswith("- ") or stripped.startswith("* "):
            bullet_text = stripped[2:].strip()
            p = doc.add_paragraph(style='List Bullet')
            p.add_run(bullet_text)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
        elif stripped.startswith("---"):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(6)
            p.paragraph_format.space_after = Pt(6)
        else:
            p = doc.add_paragraph()
            p.add_run(stripped)
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(4)

    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    doc.save(output_path)
    logger.info(f"Successfully exported Word document: {output_path}")
    return output_path


def export_to_txt(markdown_text: str, output_path: str) -> str:
    """Exports raw or stripped plain text file for easy copy/paste or archiving."""
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(markdown_text)
    logger.info(f"Successfully exported plain text note: {output_path}")
    return output_path


def export_tasks_markdown(pending_actions: List[Dict], output_path: str) -> str:
    """Creates or updates a centralized tasks checklist file (tasks.md)."""
    os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
    content = [
        f"# OpenBird Action Items & Tasks Tracker",
        f"> Automatically updated on {time.strftime('%Y-%m-%d %H:%M:%S')}",
        "",
        "## Pending Actions",
        ""
    ]
    if not pending_actions:
        content.append("*No pending action items found. Everything is clear!*")
    else:
        for a in pending_actions:
            mtg = a.get("meeting_title") or "Session"
            owner = a.get("owner") or config.user_name()
            task = a.get("task", "")
            created = a.get("created_at", "")[:10]
            content.append(f"- [ ] **{task}** (Owner: `{owner}` • From: *{mtg}* • `{created}`)")

    content.append("\n---\n")
    with open(output_path, "w", encoding="utf-8") as f:
        f.write("\n".join(content))
    logger.info(f"Successfully updated tasks tracker: {output_path}")
    return output_path
